"""Selected-run export. Snapshot ownership is independent of current GUI inputs."""
from dataclasses import asdict, replace
import json
from pathlib import Path
import numpy as np
from matplotlib.figure import Figure
from matplotlib.backends.backend_agg import FigureCanvasAgg
from .experiment_plotting import PLOT_LOCK, render_run
from .experiment_config import lane_preview
from .validation_workbook import RunTable, configuration_table, write_workbook
from .lane_benchmark import original_lane_records


def export_run(record):
    if record.data is None:
        raise ValueError("Run has no generated data")
    output=Path(record.output_directory)
    output.mkdir(parents=True,exist_ok=True)
    raw=record.snapshot.to_dict()
    tables=[t.export_table() for t in record.data.tables]
    tables.extend([
        RunTable.from_records("configured_levels.csv","Configured_Levels",raw["levels"],kind="prescribed"),
        RunTable.from_records("configured_lanes.csv","Configured_Lanes",lane_preview(record.snapshot),kind="prescribed/derived; see mode"),
        RunTable.from_records("original_lane_benchmark.csv","Original_Benchmark",original_lane_records(),kind="original independent-lane benchmark; single sigma is not two endpoint sigmas"),
        configuration_table(dict(mode=raw["mode"],noise_model=raw["noise_model"],preset_name=raw["preset_name"],output_root=raw["output_root"])),
        RunTable.from_records("plot_settings.csv","Plot_Settings",[asdict(record.plot_settings)],kind="display only"),
        RunTable.from_records("run_record.csv","Run_Record",[dict(run_id=record.run_id,mode=raw["mode"],created_at=record.created_at,
            completed_at=record.completed_at,status=record.status,output_directory=str(output))],kind="run metadata")])
    # Avoid duplicate configuration.csv generated by the existing waveform exporter.
    tables[-3].source_csv="mode_settings.csv"
    tables[-3].sheet_name="Mode_Settings"
    if record.snapshot.mode=="history_endpoints":
        for name in ("incoming","outgoing","contexts"):
            tables.append(RunTable.from_records(f"{name}_prescribed.csv",f"{name.title()}_Prescribed",raw[name],kind="prescribed proposals / overrides"))
    arrays={name:array for name,array in record.data.arrays.items()}
    arrays["experiment_snapshot_json"]=np.asarray(record.snapshot.snapshot_json)
    with PLOT_LOCK:
        if record.data.waveform is not None:
            from .export import save_run
            extras={f"experiment_{k}":v for k,v in arrays.items()}
            save_run(record.data.waveform,output,description=record.data.summary,extra_tables=tables,numerical_arrays=extras)
        else:
            np.savez_compressed(output/"waveform.npz",**arrays,metadata_json=json.dumps(dict(mode="independent_lanes",waveform_available=False,
                explanation="independent finite 1UI lane realizations; no continuous waveform or constructed 2UI data")))
            config=configuration_table(raw["base"])
            tables=[config,*tables]
            for table in tables:
                table.write_csv(output)
            write_workbook(tables,output)
            (output/"config.json").write_text(record.snapshot.snapshot_json,encoding="utf-8")
            (output/"summary.json").write_text(json.dumps(dict(mode=record.snapshot.mode,summary=record.data.summary,waveform_status="unavailable",two_ui_status="unavailable"),indent=2),encoding="utf-8")
        # All snapshots and settings belong to this selected run, not the editor.
        (output/"gui_config.json").write_text(record.snapshot.snapshot_json,encoding="utf-8")
        (output/"gui_plot_settings.json").write_text(json.dumps(asdict(record.plot_settings),indent=2),encoding="utf-8")
        views=[record.plot_settings.view]
        if record.data.waveform is None:
            views=list(dict.fromkeys([*views,"1UI pattern","Level histogram","Lane histogram"]))
        for index,view in enumerate(views):
            figure=Figure(figsize=(9,5),dpi=150)
            FigureCanvasAgg(figure)
            histogram=render_run(figure,record,replace(record.plot_settings,view=view))
            filename="selected_view" if index==0 else view.lower().replace(" ","_")
            figure.savefig(output/f"{filename}.png")
            if histogram:
                np.savez_compressed(output/f"{filename}_raw_counts.npz",**histogram)
            figure.clear()
    return output
